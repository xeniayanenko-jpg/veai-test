"""
calculator.py — вычисление среднего арифметического трёх чисел.

Среднее арифметическое — это сумма всех чисел, делённая на их количество.
Для трёх чисел формула выглядит так:

    среднее = (a + b + c) / 3

Программа умеет работать двумя способами:
  1) в интерактивном режиме — запрашивает три числа у пользователя;
  2) с аргументами командной строки: python calculator.py 2 4 9
"""

import sys


def average_of_three(a: float, b: float, c: float) -> float:
    """Возвращает среднее арифметическое трёх чисел.

    Параметры:
        a, b, c — три числа (целые или дробные).

    Возвращает:
        float — значение (a + b + c) / 3.
    """
    # Сначала складываем все три числа...
    total = a + b + c
    # ...и делим сумму на их количество (три), чтобы получить среднее.
    return total / 3


def read_number(prompt: str) -> float:
    """Читает число с клавиатуры, пока пользователь не введёт корректное значение."""
    while True:
        # input() возвращает строку — её нужно превратить в число,
        # поэтому используем float(), который принимает и "5", и "2.5".
        raw = input(prompt).strip().replace(",", ".")  # запятую меняем на точку
        try:
            return float(raw)
        except ValueError:
            # Сюда попадаем, если ввод не является числом.
            print("Ошибка: нужно ввести число. Попробуйте ещё раз.")


def main() -> None:
    """Точка входа: получает три числа и печатает их среднее арифметическое."""
    if len(sys.argv) == 4:
        # Режим командной строки: три аргумента после имени файла.
        try:
            numbers = [float(arg.replace(",", ".")) for arg in sys.argv[1:4]]
        except ValueError:
            print("Ошибка: аргументы должны быть числами.")
            return
    else:
        # Интерактивный режим: спрашиваем у пользователя три числа.
        print("Введите три числа, чтобы найти их среднее арифметическое.")
        numbers = [
            read_number("Первое число: "),
            read_number("Второе число: "),
            read_number("Третье число: "),
        ]

    # Распаковываем список из трёх элементов в отдельные переменные.
    a, b, c = numbers
    result = average_of_three(a, b, c)

    # Выводим подробный ответ, чтобы был понятен результат.
    print(f"Сумма чисел: {a} + {b} + {c} = {a + b + c}")
    print(f"Среднее арифметическое: {result}")


# Этот блок выполняется только при прямом запуске файла
# (то есть при `python calculator.py`), но не при импорте как модуля.
if __name__ == "__main__":
    main()
